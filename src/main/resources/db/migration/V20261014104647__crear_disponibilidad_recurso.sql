-- Módulo: recursos (HU06 - gestionar disponibilidad de recursos)
--
-- horario_recurso: horario semanal en que opera cada recurso. Cada fila es una franja
--   [hora_inicio, hora_fin) de un día de la semana; un recurso puede tener varias franjas
--   por día (p. ej. mañana y tarde) siempre que no se solapen (lo valida la aplicación).
--   Si un recurso no tiene ninguna fila aquí, se considera operativo a cualquier hora
--   (compatibilidad con los recursos creados antes de esta HU).
--
-- bloqueo_recurso: rangos de fechas [fecha_inicio, fecha_fin) en los que el recurso no se
--   puede prestar aunque caiga dentro de su horario (mantenimiento, reparación, etc.).
--
-- Ambas tablas solo referencian a recurso, que es del propio módulo, por eso sí llevan
-- FOREIGN KEY (misma convención que fk_recurso_prestado_recurso). ON DELETE RESTRICT porque
-- los recursos no se borran físicamente: se desactivan con eliminado_en.
--
-- Sentencias separadas y sin índices parciales para que el script corra igual en
-- PostgreSQL y en H2 (tests).

CREATE TABLE horario_recurso (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_recurso INTEGER NOT NULL,
    dia_semana VARCHAR(10) NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    CONSTRAINT fk_horario_recurso_recurso FOREIGN KEY (id_recurso) REFERENCES recurso(id) ON DELETE RESTRICT,
    CONSTRAINT chk_horario_recurso_horas CHECK (hora_fin > hora_inicio)
);

CREATE INDEX idx_horario_recurso_recurso_dia ON horario_recurso (id_recurso, dia_semana);

CREATE TABLE bloqueo_recurso (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_recurso INTEGER NOT NULL,
    fecha_inicio TIMESTAMP NOT NULL,
    fecha_fin TIMESTAMP NOT NULL,
    motivo VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_bloqueo_recurso_recurso FOREIGN KEY (id_recurso) REFERENCES recurso(id) ON DELETE RESTRICT,
    CONSTRAINT chk_bloqueo_recurso_fechas CHECK (fecha_fin > fecha_inicio)
);

CREATE INDEX idx_bloqueo_recurso_rango ON bloqueo_recurso (id_recurso, fecha_inicio, fecha_fin);
