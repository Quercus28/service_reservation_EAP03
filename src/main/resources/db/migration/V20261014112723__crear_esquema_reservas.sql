-- Módulo: reservas (HU08 - crear reserva)
--
-- servicio_prestado pertenece al módulo reservas: cada fila es la reserva que un cliente
-- hace de un servicio en un rango [fecha_inicio, fecha_fin).
--
-- DECISIÓN DE DISEÑO: id_cliente, id_servicio e id_proveedor se guardan como enteros simples,
-- sin FOREIGN KEY, igual que en el resto del esquema: ninguna tabla lleva FK hacia una tabla
-- de otro módulo (cliente y proveedor son de identidad, servicio es de servicios_catalogo).
-- La existencia de esos ids se valida en la capa de aplicación a través de los puertos del
-- módulo dueño de cada tabla.
--
-- id_proveedor se guarda aunque se pueda deducir de servicio.id_proveedor: así el chequeo de
-- disponibilidad del proveedor se resuelve con esta tabla sola, sin cruzar con una tabla de
-- otro módulo.
--
-- No hay columna de precio porque servicio todavía no tiene precio.
--
-- Sentencias separadas y sin índices parciales para que el script corra igual en
-- PostgreSQL y en H2 (tests).

CREATE TABLE servicio_prestado (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL,
    id_servicio INTEGER NOT NULL,
    id_proveedor INTEGER NOT NULL,
    fecha_inicio TIMESTAMP NOT NULL,
    fecha_fin TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'RESERVADO',
    notas VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_servicio_prestado_fechas CHECK (fecha_fin > fecha_inicio),
    CONSTRAINT chk_servicio_prestado_estado CHECK (estado IN ('RESERVADO', 'EN_PROCESO', 'COMPLETADO', 'CANCELADO', 'NO_ASISTIO'))
);

CREATE INDEX idx_servicio_prestado_cliente ON servicio_prestado (id_cliente, fecha_inicio);
CREATE INDEX idx_servicio_prestado_servicio ON servicio_prestado (id_servicio, fecha_inicio, fecha_fin);
CREATE INDEX idx_servicio_prestado_proveedor ON servicio_prestado (id_proveedor, fecha_inicio, fecha_fin);
