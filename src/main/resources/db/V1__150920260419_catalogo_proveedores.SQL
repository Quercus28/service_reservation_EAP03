CREATE TABLE proveedor (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL UNIQUE, -- Referencia a Auth (sin FK física por modularidad)
    razon_social VARCHAR(150) NOT NULL,
    nit_rut VARCHAR(50) NOT NULL UNIQUE,
    telefono VARCHAR(30),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE servicio (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proveedor INT NOT NULL,
    duracion_minutos INT NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_servicio_proveedor FOREIGN KEY (id_proveedor) REFERENCES proveedor (id) ON DELETE CASCADE
);